#!/usr/bin/env python3
"""Preflight the design sheets and generate src/RobloxObbyPeak/Generated.cs from them.

Usage: python3 tools/gen.py [--check]
Exits non-zero when any cell is unfilled or a cross-sheet reference does not resolve.
Cells marked verifiedInGame=false are listed as "awaiting in-game test" (not a build error).
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SHEETS = ROOT / "sheets"
OUT = ROOT / "src" / "RobloxObbyPeak" / "Generated.cs"


def load(name):
    return json.loads((SHEETS / f"{name}.json").read_text(encoding="utf-8"))


def cs(v):
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        return f"{v}f" if isinstance(v, float) else str(v)
    if isinstance(v, list):
        return "new[] { " + ", ".join(cs(x) for x in v) + " }"
    return json.dumps(str(v))


def preflight(sheets):
    errors, unverified = [], []
    for name, s in sheets.items():
        ids = set()
        for i, row in enumerate(s["rows"]):
            key = row.get("id", row.get("stage", i))
            for col in s["columns"]:
                if col not in row or row[col] is None or row[col] == "" or row[col] == []:
                    errors.append(f"{name}[{key}].{col}: unfilled")
            for col in row:
                if col not in s["columns"]:
                    errors.append(f"{name}[{key}].{col}: column not declared")
            if key in ids:
                errors.append(f"{name}[{key}]: duplicate id")
            ids.add(key)
            if row.get("verifiedInGame") is False:
                unverified.append(f"{name}[{key}]")
    assets = {r["id"]: r for r in sheets["roblox_assets"]["rows"]}
    hooks = {r["id"] for r in sheets["hooks"]["rows"]}
    systems = {r["id"] for r in sheets["systems"]["rows"]}
    for r in sheets["stages"]["rows"]:
        a = assets.get(r["soundId"])
        if not a or a["kind"] != "sound":
            errors.append(f"stages[{r['stage']}].soundId: '{r['soundId']}' is not a sound in roblox_assets")
    heights = [r["minHeight"] for r in sheets["stages"]["rows"]]
    if heights != sorted(heights):
        errors.append("stages.minHeight: must increase with stage")
    for r in sheets["systems"]["rows"]:
        for h in r["hooks"]:
            if h not in hooks:
                errors.append(f"systems[{r['id']}].hooks: '{h}' not in hooks sheet")
        for a in r["assets"]:
            if a not in assets:
                errors.append(f"systems[{r['id']}].assets: '{a}' not in roblox_assets sheet")
    for a in assets.values():
        for u in a["usedBy"].split(","):
            if u.strip() not in systems:
                errors.append(f"roblox_assets[{a['id']}].usedBy: '{u}' not in systems sheet")
        if a["kind"] not in ("sound", "font", "sky"):
            errors.append(f"roblox_assets[{a['id']}].kind: unknown '{a['kind']}'")
    for r in sheets["hooks"]["rows"]:
        if r["memberKind"] not in ("field", "property", "method"):
            errors.append(f"hooks[{r['id']}].memberKind: unknown '{r['memberKind']}'")
    return errors, unverified


def generate(sheets):
    L = ["// <auto-generated> from sheets/*.json by tools/gen.py. Edit the sheets, not this file. </auto-generated>",
         "namespace RobloxObbyPeak", "{",
         "    internal struct RobloxAssetRow { public string Id, Kind, SearchDir, UsedBy; public string[] Candidates, Keywords; public bool Required; }",
         "    internal struct StageRow { public int Stage; public float MinHeight; public string BannerText, SoundId; }",
         "    internal struct HookRow { public string Id, TypeName, Member, MemberKind, Purpose, Fallback; public bool IsStatic; }",
         "    internal struct SystemRow { public string Id, Description, ConfigKey; public bool Default; public string[] Hooks, Assets; }",
         "", "    internal static class Sheets", "    {"]
    L.append("        public static readonly RobloxAssetRow[] RobloxAssets = {")
    for r in sheets["roblox_assets"]["rows"]:
        L.append(f"            new RobloxAssetRow {{ Id = {cs(r['id'])}, Kind = {cs(r['kind'])}, Candidates = {cs(r['candidates'])}, SearchDir = {cs(r['searchDir'])}, Keywords = {cs(r['keywords'])}, Required = {cs(r['required'])}, UsedBy = {cs(r['usedBy'])} }},")
    L.append("        };")
    L.append("        public static readonly StageRow[] Stages = {")
    for r in sheets["stages"]["rows"]:
        L.append(f"            new StageRow {{ Stage = {r['stage']}, MinHeight = {float(r['minHeight'])}f, BannerText = {cs(r['bannerText'])}, SoundId = {cs(r['soundId'])} }},")
    L.append("        };")
    L.append("        public static readonly HookRow[] Hooks = {")
    for r in sheets["hooks"]["rows"]:
        L.append(f"            new HookRow {{ Id = {cs(r['id'])}, TypeName = {cs(r['typeName'])}, Member = {cs(r['member'])}, MemberKind = {cs(r['memberKind'])}, IsStatic = {cs(r['isStatic'])}, Purpose = {cs(r['purpose'])}, Fallback = {cs(r['fallback'])} }},")
    L.append("        };")
    L.append("        public static readonly SystemRow[] Systems = {")
    for r in sheets["systems"]["rows"]:
        L.append(f"            new SystemRow {{ Id = {cs(r['id'])}, Description = {cs(r['description'])}, ConfigKey = {cs(r['configKey'])}, Default = {cs(r['default'])}, Hooks = {cs(r['hooks'])}, Assets = {cs(r['assets'])} }},")
    L.append("        };")
    L += ["    }", "}", ""]
    return "\n".join(L).replace(".0f", "f")


def main():
    sheets = {n: load(n) for n in ("roblox_assets", "stages", "hooks", "systems")}
    errors, unverified = preflight(sheets)
    print(f"preflight: {sum(len(s['rows']) for s in sheets.values())} rows across {len(sheets)} sheets")
    for e in errors:
        print("  ERROR", e)
    if unverified:
        print(f"  awaiting in-game test ({len(unverified)}): " + ", ".join(unverified))
    if errors:
        sys.exit(1)
    print("preflight clean")
    code = generate(sheets)
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != code:
            print("Generated.cs is out of date; run tools/gen.py")
            sys.exit(1)
        return
    OUT.write_text(code, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
